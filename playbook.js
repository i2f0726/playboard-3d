  // 折れ線を等速でなぞったことにする。wait ミリ秒だけその場で待ってから動き出す
  function wp(points, ms, wait = 0) {
    const segs = []; let L = 0;
    for (let i = 1; i < points.length; i++) { const d = dist(points[i - 1], points[i]); segs.push(d); L += d; }
    const out = [[...points[0], 0]]; let acc = 0;
    if (wait) out.push([...points[0], wait]);
    for (let i = 1; i < points.length; i++) {
      for (let s = 1; s <= 6; s++) {
        const k = s / 6, p = [points[i - 1][0] + (points[i][0] - points[i - 1][0]) * k, points[i - 1][1] + (points[i][1] - points[i - 1][1]) * k];
        out.push([+p[0].toFixed(2), +p[1].toFixed(2), wait + Math.round((acc + segs[i - 1] * k) / L * ms)]);
      }
      acc += segs[i - 1];
    }
    return out;
  }
  // 時刻つきの通り道 [[x, y, ミリ秒]...] を、なめらかな曲線（カトマル・ロム）にする
